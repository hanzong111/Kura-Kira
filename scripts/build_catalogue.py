"""Merge catalogue/raw/*.psv into catalogue/merchants.csv.

- earlier files win when two entries claim the same name/alias with a different bucket/category
  (house > transport/health/pet > grocery > leisure/sport/golf > food), and every such conflict is reported;
- ordinary words that are also brand names (dome, texas, village, five, plus...) are marked "=alias":
  they only match when they are the whole place name, never inside longer text.

    python scripts/build_catalogue.py
"""

from __future__ import annotations

import csv
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = ROOT / "catalogue" / "raw"
OUT = ROOT / "catalogue" / "merchants.csv"
TABLE = ROOT / "catalogue" / "MERCHANTS.md"
TITLES = {"house": "Ours", "transport_health_pet": "Petrol, toll, transport, health, toiletries, pet",
          "grocery": "Groceries, convenience, household", "leisure_sport_golf": "Leisure, sport, golf",
          "food": "Food & drink"}
ORDER = ["house", "transport_health_pet", "grocery", "leisure_sport_golf", "food"]

# ordinary words / place names that must not match inside a longer message
EXACT_ONLY = {
    "five", "plus", "smart", "elite", "dash", "sprint", "silk", "duke", "mex", "caring", "absolute", "brit", "spec",
    "compound", "cotton", "georgetown", "guthrie", "mesra", "village", "jaya", "pacific", "hero", "sunshine", "billion",
    "selections", "checkers", "aneka", "sams", "bens", "texas", "manhattan", "dome", "dolly", "lavender", "kayu", "nene",
    "koi", "pelita", "hailam", "anytime", "breakout", "superstar", "bump", "babel", "playa", "clearwater", "danau",
    "lagoon", "ponderosa", "dagang", "kukus", "kerabu", "soto", "big apple", "san francisco", "line clear",
    "super kitchen", "maxx", "aurum", "zepp", "staffield", "kinrara", "monterez", "gama", "nirwana", "lulu", "giant",
    "subway", "sakae", "yayoi", "dadi", "tambun", "legends", "saujana", "glenmarie", "impact golf", "orna",
    "tiara melaka", "damai laut", "meru valley", "palm resort", "palm garden", "templer park", "litter", "pad", "lotion",
    "soap", "razor", "deodorant", "physio", "optical", "hospital", "specialist", "teh", "kopi", "roti", "apam", "sate",
    "abc", "big pharma", "ole ole", "superbowl", "concert", "gym", "swimming", "badminton", "bowling", "karaoke",
}


def squash(s: str) -> str:
    return re.sub(r"[^a-z0-9]", "", s.lower())


def write_table(rows: list[dict]) -> None:
    from collections import Counter
    out = ["# Merchant catalogue", "",
           "Generated by `scripts/build_catalogue.py` from `catalogue/raw/*.psv` (web research, 2026-10-18).",
           "The bot uses it when the model gives no bucket or isn't sure; places you've corrected always win.",
           "Aliases in *italics* only match when they're the whole place name.", "",
           "| Section | Merchants |", "|---|---|"]
    count = Counter(r["group"] for r in rows)
    out += [f"| {TITLES[g]} | {count[g]} |" for g in ORDER] + [f"| **Total** | **{len(rows)}** |", ""]
    for g in ORDER:
        out += [f"## {TITLES[g]}", "", "| Name | Also typed as | Bucket | Category |", "|---|---|---|---|"]
        for r in (x for x in rows if x["group"] == g):
            aliases = ", ".join(f"*{a[1:]}*" if a.startswith("=") else a for a in r["aliases"])
            out.append(f"| {r['name']} | {aliases.replace('|', '/')} | {r['bucket']} | {r['category']} |")
        out.append("")
    TABLE.write_text("\n".join(out), encoding="utf-8")


def main() -> int:
    owner: dict[str, tuple[str, str, str, str]] = {}   # squashed alias -> (name, bucket, category, file)
    rows: dict[str, dict] = {}                          # name -> row
    conflicts = []
    for stem in ORDER:
        with open(RAW / f"{stem}.psv", newline="", encoding="utf-8") as f:
            for r in csv.DictReader(f, delimiter="|"):
                name, bucket, category = r["name"].strip(), r["bucket"].strip(), r["category"].strip()
                if not name:
                    continue
                kept = []
                for alias in [name] + [a.strip() for a in (r.get("aliases") or "").split(";") if a.strip()]:
                    key = squash(alias)
                    if not key:
                        continue
                    prev = owner.get(key)
                    if prev and (prev[1], prev[2]) != (bucket, category):
                        conflicts.append(f"'{alias}': {prev[0]} ({prev[1]}/{prev[2]}, {prev[3]}) kept over "
                                         f"{name} ({bucket}/{category}, {stem})")
                        continue
                    if prev:
                        continue  # same meaning, already listed
                    owner[key] = (name, bucket, category, stem)
                    if alias != name:
                        kept.append(("=" + alias) if alias.lower() in EXACT_ONLY else alias)
                if squash(name) in owner and owner[squash(name)][0] == name:
                    row = rows.setdefault(name, {"name": name, "aliases": [], "bucket": bucket, "category": category,
                                                 "group": stem})
                    row["aliases"] += kept
    with open(OUT, "w", newline="", encoding="utf-8") as f:
        f.write("# Generated by scripts/build_catalogue.py from catalogue/raw/*.psv (web research, 2026-10-18).\n")
        f.write("# '=alias' matches only the whole place name.\n")
        w = csv.writer(f, delimiter="|", lineterminator="\n")
        w.writerow(["name", "aliases", "bucket", "category", "group"])
        for row in rows.values():
            name = ("=" + row["name"]) if row["name"].lower() in EXACT_ONLY else row["name"]
            w.writerow([name, ";".join(row["aliases"]), row["bucket"], row["category"], row["group"]])
    write_table(list(rows.values()))
    print(f"{len(rows)} merchants, {len(owner)} names/aliases -> {OUT.relative_to(ROOT)}, {TABLE.relative_to(ROOT)}")
    for c in conflicts:
        print("conflict:", c)
    return 0


if __name__ == "__main__":
    sys.exit(main())
